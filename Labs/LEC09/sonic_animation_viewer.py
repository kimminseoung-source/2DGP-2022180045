import pico2d as p

WIDTH, HEIGHT = 800, 600
REPEAT_COUNT = 5
HOLD_SECONDS = 0.5
DEFAULT_FPS = 10
DISPLAY_FRACTION = 0.65
RENDER_FPS = 60


def main():
    """뷰어의 실행 진입점."""
    p.open_canvas(WIDTH, HEIGHT)
    try:
        p.clear_canvas()
        p.update_canvas()
    finally:
        p.close_canvas()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
